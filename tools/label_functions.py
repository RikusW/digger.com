#!/usr/bin/env python3
"""Label every function boundary in digger.lst and write FUNCTIONS.md.

A "function boundary" is any address that is the target of a CALL in the
disassembly, plus the program entry point and the two interrupt handlers
(INT 8 at CS:0x0397 and INT 9 at CS:0x0E48).  Boundaries that already carry a
`; --- name ---` comment keep it; the rest get `; --- loc_XXXX ---`.

The script is idempotent: running it again does not add duplicate labels.

Usage: python3 tools/label_functions.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LST = ROOT / "digger.lst"
OUT = ROOT / "FUNCTIONS.md"

CALL_RE = re.compile(r"\bcall\s+0x([0-9a-f]+)")
LINE_RE = re.compile(r"^ +([0-9a-f]{3,4}):\t(.*)$")
LABEL_RE = re.compile(r"^; --- (.*?) ---$")

EXTRA_ENTRIES = {
    0x0100: "entry point",
    0x0397: "INT 8 handler",
    0x0E48: "INT 9 handler",
}


def parse_lines(lines):
    """Return address -> instruction text, and file order."""
    ins = {}
    order = []
    for line in lines:
        m = LINE_RE.match(line)
        if not m:
            continue
        addr = int(m.group(1), 16)
        text = m.group(2).split("\t")[-1].strip()
        ins[addr] = text
        order.append(addr)
    return ins, order


def existing_label(lines, addr):
    """Label comment immediately before the address line, if any."""
    for i, line in enumerate(lines):
        m = LINE_RE.match(line)
        if m and int(m.group(1), 16) == addr:
            if i > 0:
                lm = LABEL_RE.match(lines[i - 1])
                if lm:
                    return lm.group(1)
            return None
    return None


def main():
    lines = LST.read_text().splitlines()
    ins, order = parse_lines(lines)

    targets = set(EXTRA_ENTRIES)
    for text in ins.values():
        m = CALL_RE.search(text)
        if m:
            addr = int(m.group(1), 16)
            if addr in ins:
                targets.add(addr)

    # Insert labels for unlabeled boundaries (before the address line).
    out = []
    inserted = set()
    for line in lines:
        m = LINE_RE.match(line)
        if m:
            addr = int(m.group(1), 16)
            if addr in targets and addr not in inserted:
                if existing_label(lines, addr) is None:
                    out.append("; --- loc_%04X ---" % addr)
                inserted.add(addr)
        out.append(line)

    # Collapse duplicate label runs before an address, keeping the longest.
    collapsed = []
    i = 0
    while i < len(out):
        if out[i].startswith("; --- "):
            run = []
            j = i
            while j < len(out) and out[j].startswith("; --- "):
                run.append(out[j])
                j += 1
            if j < len(out) and LINE_RE.match(out[j]):
                named = [x for x in run if not x.startswith("; --- loc_")]
                collapsed.append(max(named or run, key=len))
                i = j
                continue
            collapsed.extend(run)
            i = j
            continue
        collapsed.append(out[i])
        i += 1
    LST.write_text("\n".join(collapsed) + "\n")

    # Rebuild the map with final labels.
    lines = collapsed
    rows = []
    for addr in sorted(targets):
        name = existing_label(lines, addr)
        if name is None:
            name = "loc_%04X" % addr
        note = EXTRA_ENTRIES.get(addr, "")
        text = ins.get(addr, "")
        rows.append((addr, addr - 0x100, name, note, text))

    md = ["# Function boundary map", ""]
    md.append("Every CALL target in `digger.lst`, plus the entry point and the")
    md.append("two interrupt handlers.  `file` is the offset in `digger.com`")
    md.append("(`file = CS - 0x100`).  Names come from the verified/probable")
    md.append("labels; unlabeled boundaries are `loc_XXXX`.  Generated by")
    md.append("`tools/label_functions.py`.  Total: **%d** boundaries." % len(rows))
    md.append("")
    md.append("| CS:IP | file | name | note | first instruction |")
    md.append("|---:|---:|---|---|---|")
    for addr, foff, name, note, text in rows:
        md.append("| `0x%04X` | `0x%04X` | `%s` | %s | `%s` |" %
                  (addr, foff, name, note, text.replace("|", "\\|")))
    md.append("")
    OUT.write_text("\n".join(md))
    print("labeled %d boundaries -> %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
